#!/usr/bin/env node
// Copies contract ABIs from contracts/out (after `forge build`) into shared/src/abi as typed `as const`
// TypeScript modules, so viem and wagmi infer function names and argument types.
//
// Usage: npm run abi -w shared   (the root `npm run build` runs forge build first)
//
// If contracts/out is missing (forge not installed), the committed ABIs are kept and a warning is printed.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', '..', 'contracts', 'out');
const abiDir = join(here, '..', 'src', 'abi');

/** [artifact file, contract name, exported const name] */
const CONTRACTS = [
  ['ChannelCore.sol', 'ChannelCore'],
  ['SubscriptionPlans.sol', 'SubscriptionPlans'],
  ['CustodyAdapter.sol', 'CustodyAdapter'],
  ['ClaimToken.sol', 'ClaimToken'],
  ['DisputeManager.sol', 'DisputeManager'],
  ['AgentPolicy.sol', 'AgentPolicy'],
  ['ECDSAVerifier.sol', 'ECDSAVerifier'],
  ['HybridMLDSAVerifier.sol', 'HybridMLDSAVerifier'],
  ['LocalMessenger.sol', 'LocalMessenger'],
  // tUSD8 is an external token. Its permit/nonces/DOMAIN_SEPARATOR ABI comes from OpenZeppelin's interface.
  ['IERC20Permit.sol', 'IERC20Permit'],
];

if (!existsSync(outDir)) {
  if (existsSync(join(abiDir, 'index.ts'))) {
    console.warn(`[copy-abis] ${outDir} not found; keeping committed ABIs. Run \`forge build\` in /contracts to refresh.`);
    process.exit(0);
  }
  console.error(`[copy-abis] ${outDir} not found and no committed ABIs. Run \`forge build\` in /contracts first.`);
  process.exit(1);
}

mkdirSync(abiDir, { recursive: true });
const header = '// AUTO-GENERATED by shared/scripts/copy-abis.mjs from contracts/out. Do not edit.\n';
const exports = [];
for (const [file, name] of CONTRACTS) {
  const artifactPath = join(outDir, file, `${name}.json`);
  if (!existsSync(artifactPath)) {
    console.error(`[copy-abis] missing artifact ${artifactPath}`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(artifactPath, 'utf8'));
  const constName = `${name[0].toLowerCase()}${name.slice(1)}Abi`;
  writeFileSync(join(abiDir, `${name}.ts`), `${header}export const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`);
  exports.push(`export { ${constName} } from './${name}.js';`);
}
writeFileSync(join(abiDir, 'index.ts'), `${header}${exports.join('\n')}\n`);
console.log(`[copy-abis] wrote ${CONTRACTS.length} ABIs to ${abiDir}`);
